"""Deterministic subtle paper grain. Pillow is only an optional authoring tool."""
from pathlib import Path
from PIL import Image
import base64
import io
import random

root = Path(__file__).resolve().parent.parent
rng = random.Random(20261103)
image = Image.new('RGBA', (64, 64))
image.putdata([(96, 55, 31, rng.choice([0, 0, 0, 0, 2, 3, 5, 7])) for _ in range(64 * 64)])
buffer = io.BytesIO()
image.save(buffer, format='PNG', optimize=True)
target = root / 'miniprogram' / 'assets' / 'paper-grain.png'
target.write_bytes(buffer.getvalue())
encoded = base64.b64encode(buffer.getvalue()).decode('ascii')
# WXSS cannot reliably load local background URLs; embed this local authored tile.
style = '/* Original subtle paper grain, generated by scripts/generate-paper.py. */\npage { background-image: url("data:image/png;base64,' + encoded + '"); background-size: 128rpx 128rpx; }\n'
(root / 'miniprogram' / 'styles' / 'paper.wxss').write_text(style, encoding='utf-8')
print(f'Created local paper texture: {len(buffer.getvalue())} bytes')
